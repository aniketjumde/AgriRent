# Database configuration: Supabase PostgreSQL (via DATABASE_URL, SUPABASE_DB_URL, or discrete env vars), fallback to local SQLite
DATABASE_URL = os.environ.get('DATABASE_URL') or os.environ.get('SUPABASE_DB_URL')
DB_NAME = os.environ.get('DB_NAME', '')
DB_USER = os.environ.get('DB_USER', '')
DB_PASSWORD = os.environ.get('DB_PASSWORD', '')
DB_HOST = os.environ.get('DB_HOST', '')
DB_PORT = os.environ.get('DB_PORT', '')

if DATABASE_URL:
    parsed_db = urllib.parse.urlparse(DATABASE_URL)
    query_params = urllib.parse.parse_qs(parsed_db.query)
    ssl_mode = query_params.get('sslmode', ['require'])[0]
    
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': parsed_db.path.lstrip('/'),
            'USER': parsed_db.username or '',
            'PASSWORD': urllib.parse.unquote(parsed_db.password or ''),
            'HOST': parsed_db.hostname or '',
            'PORT': parsed_db.port or 5432,
            'OPTIONS': {
                'sslmode': ssl_mode,
            },
            'CONN_MAX_AGE': int(os.environ.get('CONN_MAX_AGE', 600)),
        }
    }
elif DB_NAME and DB_USER:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': DB_NAME,
            'USER': DB_USER,
            'PASSWORD': DB_PASSWORD,
            'HOST': DB_HOST,
            'PORT': DB_PORT,
            'OPTIONS': {
                'sslmode': os.environ.get('DB_SSLMODE', 'prefer'),
            },
            'CONN_MAX_AGE': int(os.environ.get('CONN_MAX_AGE', 600)),
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }

